# Задача 2: Методы класса и параметр self
# Создай класс Calculator (калькулятор).
# Требования:
# В конструкторе __init__ инициализируй атрибут result со значением 0.
# Добавь метод add, который принимает число (кроме self) и увеличивает result на это число.
# Добавь метод subtract, который принимает число (кроме self) и уменьшает result на это число.
# Добавь метод reset, который сбрасывает result до 0.
# После написания класса:
# Создай объект calc класса Calculator.
# Вызови метод add с аргументом 10.
# Вызови метод subtract с аргументом 5.
# Выведи на экран атрибут result объекта calc.
# Вызови метод reset.
# Выведи result снова.

class Calculator:
    def __init__(self):
        self.result = 0


    def add(self, number):
        self.result += number


    def subtract(self, number):
        self.result -= number


    def reset(self):
        self.result = 0


calc = Calculator()
calc.add(10)
calc.subtract(5)
print(calc.result)
calc.reset()
print(calc.result)