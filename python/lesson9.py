# Задача 1: Конструктор класса и атрибуты
# Создай класс Book.
# Требования:
# В конструкторе __init__ определи три атрибута:
# title (название книги)
# author (автор)
# pages (количество страниц, целое число).
# Атрибуты должны устанавливаться при создании объекта.
# После написания класса:
# Создай объект my_book класса Book с аргументами:
# "Война и мир", "Лев Толстой", 1300.
# Выведи на экран атрибут author объекта my_book.

class Book:
    def __init__(self, title, author, pages):
        self.title = title
        self.author = author
        self.pages = pages


